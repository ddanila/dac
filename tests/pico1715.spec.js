import {test,expect} from '@playwright/test';
test('classic workstation boots, types, debugs and exports a disk',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await expect(page.locator('#power')).toBeEnabled({timeout:30000});
 await page.selectOption('#machine','3');await expect(page.locator('#p1715-status')).toContainText('ready');
 await page.click('#power');await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:30000});
 await page.locator('#screen').focus();await page.keyboard.type('DIR');await page.keyboard.press('Enter');
 await expect(page.locator('#p1715-text')).toContainText('HELLO',{timeout:15000});
 await page.locator('#debug-controls').evaluate(e=>e.open=true);
 await page.click('#debug-controls [data-pause]');await expect(page.locator('#debug-controls [data-step]')).toBeEnabled();
 const before=await page.locator('#debug-controls [data-registers]').textContent();
 await page.click('#debug-controls [data-step]');await expect(page.locator('#debug-controls [data-registers]')).not.toHaveText(before);
 await page.locator('#debug-controls [data-address]').fill('0000');await page.click('#debug-controls [data-memory]');
 await expect(page.locator('#debug-controls [data-bytes]')).toContainText('RAM');
 const download=page.waitForEvent('download');await page.click('#p1715-export');expect((await download).suggestedFilename()).toBe('pico1715-working.img');
 await page.click('#power');await expect(page.locator('#status')).toHaveText('Powered off');
 await page.selectOption('#machine','2');await expect(page.locator('#pico1715-panel')).toBeHidden();
 expect(errors).toEqual([]);
});
for(const backend of ['model','firmware'])test(`${backend}: writes, save/resume, breakpoint and reset`,async({page})=>{
 test.setTimeout(180000);
 await page.goto('/');await expect(page.locator('#power')).toBeEnabled({timeout:30000});await page.selectOption('#machine','3');
 await expect(page.locator('#p1715-status')).toContainText('ready');await page.selectOption('#p1715-backend',backend);
 await page.check('#p1715-write');await page.selectOption('#p1715-speed','0');await page.click('#power');
 await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:90000});
 await page.fill('#p1715-paste','PIP COPY.TXT=HELLO.TXT\n');await page.click('#p1715-type');
 await expect(page.locator('#p1715-stats')).toContainText(/writes [1-9]/,{timeout:60000});
 await expect(page.locator('#p1715-stats')).toContainText('Keyboard queued 0',{timeout:30000});
 // Wait for the command's next prompt, not just its echoed text.
 await expect.poll(async()=>((await page.locator('#p1715-text').textContent()).match(/A>/g)||[]).length,{timeout:60000}).toBeGreaterThanOrEqual(2);
 await page.click('#p1715-export');await expect(page.locator('#p1715-status')).toHaveText('Disk saved locally.',{timeout:30000});
 await page.locator('#debug-controls').evaluate(e=>e.open=true);await page.fill('#debug-controls [data-execution]','c0b9');
 await page.click('#debug-controls [data-run-to]');await expect(page.locator('#debug-controls [data-step]')).toBeEnabled({timeout:30000});
 await expect(page.locator('#debug-controls [data-registers]')).toContainText('c0b9');
 await page.click('#debug-controls [data-clear-break]');await page.click('#reset');await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:90000});
 await page.click('#power');await expect(page.locator('#status')).toHaveText('Powered off',{timeout:30000});
 await page.click('#power');await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:90000});
 await page.fill('#p1715-paste','TYPE COPY.TXT\n');await page.click('#p1715-type');
 await expect(page.locator('#p1715-text')).toContainText('Native CP/M Plus on Robotron 1715',{timeout:60000});
 await page.click('#power');await expect(page.locator('#status')).toHaveText('Powered off',{timeout:30000});
 await page.screenshot({path:test.info().outputPath(`classic-${backend}.png`)});
});
test('classic rejects malformed media and unsupported paste without replacing the session',async({page})=>{
 await page.goto('/');await expect(page.locator('#power')).toBeEnabled({timeout:30000});await page.selectOption('#machine','3');
 await expect(page.locator('#p1715-status')).toContainText('ready');
 await page.locator('#p1715-rom').setInputFiles({name:'bad.rom',mimeType:'application/octet-stream',buffer:Buffer.alloc(7)});
 await page.locator('#p1715-disk').setInputFiles({name:'bad.img',mimeType:'application/octet-stream',buffer:Buffer.alloc(9)});
 await page.click('#p1715-import');await expect(page.locator('#p1715-status')).toContainText('Expected a 2048-byte');
 await page.click('#power');await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:30000});
 await page.fill('#p1715-paste','unsupported ☃');await page.click('#p1715-type');await expect(page.locator('#p1715-status')).toContainText('ASCII');
 await expect(page.locator('#p1715-stats')).toContainText('Keyboard queued 0');
});
test('saved copy survives reload and failed persistence leaves the session usable',async({page})=>{
 test.setTimeout(90000);
 await page.goto('/?machine=1715');await expect(page.locator('#p1715-status')).toContainText('ready',{timeout:30000});
 await page.check('#p1715-write');await page.selectOption('#p1715-speed','0');await page.click('#power');
 await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:30000});
 await page.fill('#p1715-paste','PIP COPY.TXT=HELLO.TXT\n');await page.click('#p1715-type');
 await expect.poll(async()=>((await page.locator('#p1715-text').textContent()).match(/A>/g)||[]).length).toBeGreaterThanOrEqual(2);
 await page.click('#power');await expect(page.locator('#status')).toHaveText('Powered off');
 await page.reload();await expect(page.locator('#p1715-status')).toContainText('Restored saved disk',{timeout:30000});
 await page.click('#power');await expect(page.locator('#p1715-text')).toContainText('A>',{timeout:30000});
 await page.fill('#p1715-paste','TYPE COPY.TXT\n');await page.click('#p1715-type');await expect(page.locator('#p1715-text')).toContainText('Native CP/M Plus',{timeout:30000});
 await page.evaluate(()=>{window.originalTransaction=IDBDatabase.prototype.transaction;IDBDatabase.prototype.transaction=function(stores,mode,...args){if(mode==='readwrite')throw Error('Simulated quota failure');return window.originalTransaction.call(this,stores,mode,...args);};});
 await page.click('#p1715-export');await expect(page.locator('#p1715-status')).toContainText('Simulated quota failure');
 await expect(page.locator('#power')).toBeEnabled();await expect(page.locator('#power-label')).toHaveText('Power off');
 await page.evaluate(()=>{IDBDatabase.prototype.transaction=window.originalTransaction;});
 await page.click('#p1715-export');await expect(page.locator('#p1715-status')).toHaveText('Disk saved locally.');
 const worker=page.workers().find(w=>w.url().includes('pico1715.worker'));
 await worker.evaluate(()=>setTimeout(()=>{throw Error('Simulated worker failure');},100));
 await expect(page.locator('#p1715-status')).toContainText('Simulated worker failure');await expect(page.locator('#power-label')).toHaveText('Power on');
 await page.click('#p1715-restore');await expect(page.locator('#p1715-status')).toContainText('Restored saved disk');
});
